"""Write fixed copies of the static GTFS feeds to data/processed/gtfs_fixed/.

Streams files with the stdlib (low memory). No network access.
Fixes (see FIX_REPORT.md written next to the output):
  metro   : calendar window moved to end 2027-12-31 (labelled assumption: same weekly pattern).
  namo    : routes.route_type 3 (bus) -> 2 (rail).
  shared  : calendar start_date 20254501 (invalid) -> 20250101; end extended to 2027-12-31.
  all     : __MACOSX junk dropped.
Not fixed (no source data): metro Sunday trips and thin Saturday trips are reported only.
"""
import csv
import shutil
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw"
OUT = ROOT / "data" / "processed" / "gtfs_fixed"
NEW_END = "20271231"

FEEDS = {
    "bus_v1-2": ROOT / "delhi_buses_static_gtfs_v1-2",
    "metro": RAW / "dmrc_static_gtfs_v1",
    "namo_bharat": RAW / "ncrtc_static_gtfs_v1" / "ncrtc_w_shapes_v1",
    "shared_mobility": RAW / "shared_mobility_gtfs_v1",
}

report = []


def rewrite(src, dst, fn):
    """Stream-rewrite a CSV, applying fn(row) in place. Returns row count."""
    n = 0
    with open(src, newline="", encoding="utf-8-sig") as fi, \
            open(dst, "w", newline="", encoding="utf-8") as fo:
        r = csv.DictReader(fi)
        w = csv.DictWriter(fo, fieldnames=r.fieldnames, lineterminator="\n")
        w.writeheader()
        for row in r:
            fn(row)
            w.writerow(row)
            n += 1
    return n


def count_col(path, col):
    c = Counter()
    with open(path, newline="", encoding="utf-8-sig") as f:
        for row in csv.DictReader(f):
            c[row[col]] += 1
    return c


def copy_feed(name):
    src, dst = FEEDS[name], OUT / name
    dst.mkdir(parents=True, exist_ok=True)
    for p in src.glob("*"):
        if p.is_file() and p.suffix in (".txt", ".md"):
            shutil.copy2(p, dst / p.name)
    return src, dst


def fix_calendar(name, start_fix=None):
    src, dst = FEEDS[name], OUT / name
    before = [r for r in csv.DictReader(open(src / "calendar.txt", newline=""))]

    def fn(row):
        if start_fix and not (row["start_date"].isdigit() and row["start_date"][4:6] <= "12"
                              and row["start_date"][6:] <= "31"):
            row["start_date"] = start_fix
        if row["end_date"] < NEW_END:
            row["end_date"] = NEW_END

    rewrite(src / "calendar.txt", dst / "calendar.txt", fn)
    after = [r for r in csv.DictReader(open(dst / "calendar.txt", newline=""))]
    for b, a in zip(before, after):
        report.append(f"| {name} | calendar `{b['service_id']}` | {b['start_date']}..{b['end_date']} | "
                      f"{a['start_date']}..{a['end_date']} |")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name in FEEDS:
        copy_feed(name)

    # Metro: calendar
    fix_calendar("metro")
    trips = count_col(FEEDS["metro"] / "trips.txt", "service_id")
    sunday_note = (f"Metro trips per service: {dict(trips)}. Sunday has {trips.get('sunday', 0)} trips, "
                   f"Saturday {trips.get('saturday', 0)}. Not fixed: no source data; "
                   "inventing trips would be fake. Treat metro Sunday/Saturday as no-service in routing, "
                   "or ask the organisers for an updated DMRC feed.")

    # Namo Bharat: route_type
    nb_before = count_col(FEEDS["namo_bharat"] / "routes.txt", "route_type")
    rewrite(FEEDS["namo_bharat"] / "routes.txt", OUT / "namo_bharat" / "routes.txt",
            lambda row: row.__setitem__("route_type", "2"))
    nb_after = count_col(OUT / "namo_bharat" / "routes.txt", "route_type")

    # Shared mobility: bad date + expired
    fix_calendar("shared_mobility", start_fix="20250101")

    lines = [
        "# GTFS fix report",
        "",
        "Generated by `scripts/gtfs_fix.py`. Inputs are untouched; fixed copies are in this folder.",
        "",
        "## Fixes",
        "",
        "| Feed | Item | Before | After |",
        "| --- | --- | --- | --- |",
        *report,
        f"| namo_bharat | routes.route_type counts | {dict(nb_before)} (3 = bus) | {dict(nb_after)} (2 = rail) |",
        "",
        "## Notes",
        "",
        f"- Calendar fixes move `end_date` to {NEW_END}. The weekly pattern is the original one. "
        "This is an assumption: the real DMRC timetable after 2025 may differ.",
        "- Shared mobility `start_date` 20254501 is not a real date (month 45). Set to 20250101.",
        f"- {sunday_note}",
        "- Bus v1-2: no fix needed (calendar 2025..2040). Copied unchanged.",
        "- Namo Bharat calendar runs to 2029; unchanged.",
        "- `__MACOSX` junk folders and non-GTFS files are not copied.",
        "",
        "## Row counts per output file",
        "",
        "| Feed | File | Rows |",
        "| --- | --- | --- |",
    ]
    for name in FEEDS:
        for p in sorted((OUT / name).glob("*.txt")):
            with open(p, "rb") as f:
                n = sum(1 for _ in f) - 1
            lines.append(f"| {name} | {p.name} | {n} |")
    (OUT / "FIX_REPORT.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
